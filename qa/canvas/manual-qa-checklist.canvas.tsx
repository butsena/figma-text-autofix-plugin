type Shot = { id: string; src: string };

type ClipboardLike = {
  items?: ArrayLike<{ type: string; getAsFile: () => File | null }>;
  files?: FileList | ArrayLike<File>;
};

function firstImageFromClipboard(data: ClipboardLike | null | undefined): File | null {
  if (!data) return null;
  if (data.items) {
    for (let i = 0; i < data.items.length; i++) {
      const item = data.items[i];
      if (!item.type.startsWith("image/")) continue;
      const file = item.getAsFile();
      if (file) return file;
    }
  }
  if (data.files) {
    for (let i = 0; i < data.files.length; i++) {
      const file = data.files[i];
      if (file?.type.startsWith("image/")) return file;
    }
  }
  return null;
}

function ScreenshotField({
  fieldId,
  armed,
  onArm,
  shots,
  onChange,
}: {
  fieldId: string;
  armed: boolean;
  onArm: (id: string) => void;
  shots: Shot[];
  onChange: (updater: (prev: Shot[]) => Shot[]) => void;
}) {
  const theme = useHostTheme();
  const inputRef = useRef<HTMLInputElement>(null);
  const pasteRef = useRef<HTMLTextAreaElement>(null);

  const addFiles = (files: File[]) => {
    const images = files.filter((file) => file.type.startsWith("image/"));
    if (!images.length) return;
    for (const file of images) {
      const reader = new FileReader();
      reader.onload = () => {
        const src = String(reader.result ?? "");
        if (!src) return;
        onChange((prev) => {
          if (prev.some((shot) => shot.src === src)) return prev;
          return [
            ...prev,
            { id: `${Date.now()}-${Math.random().toString(36).slice(2, 8)}`, src },
          ];
        });
      };
      reader.readAsDataURL(file);
    }
  };

  const takePaste = (data: ClipboardLike | null | undefined): boolean => {
    const file = firstImageFromClipboard(data);
    if (!file) return false;
    addFiles([file]);
    return true;
  };

  useEffect(() => {
    if (!armed) return;
    pasteRef.current?.focus();
    const onPaste = (event: Event) => {
      const clipboard = (event as { clipboardData?: ClipboardLike }).clipboardData;
      if (!takePaste(clipboard)) return;
      event.preventDefault();
      event.stopPropagation();
    };
    window.addEventListener("paste", onPaste, true);
    return () => {
      window.removeEventListener("paste", onPaste, true);
    };
  }, [armed, fieldId]);

  return (
    <Stack gap={6} style={{ minWidth: 200 }}>
      <div
        onClick={(event: { stopPropagation: () => void }) => {
          event.stopPropagation();
          onArm(fieldId);
          pasteRef.current?.focus();
        }}
        onDragOver={(event: { preventDefault: () => void }) => event.preventDefault()}
        onDrop={(event: {
          preventDefault: () => void;
          dataTransfer: { files: FileList };
        }) => {
          event.preventDefault();
          addFiles(Array.from(event.dataTransfer.files));
        }}
        style={{
          position: "relative",
          padding: 8,
          border: `1px solid ${armed ? theme.accent.primary : theme.stroke.secondary}`,
          background: armed ? theme.fill.secondary : theme.fill.tertiary,
          cursor: "text",
          minHeight: 56,
        }}
      >
        <textarea
          ref={pasteRef}
          rows={2}
          value=""
          onChange={() => undefined}
          onPaste={(event: { preventDefault: () => void }) => {
            event.preventDefault();
          }}
          aria-label="Вставить скриншот"
          style={{
            position: "absolute",
            inset: 0,
            width: "100%",
            height: "100%",
            opacity: 0,
            border: 0,
            padding: 0,
            resize: "none",
            cursor: "text",
          }}
        />
        <Text as="span" size="small" tone={armed ? "primary" : "secondary"}>
          {armed ? "Теперь Cmd+V / Ctrl+V" : "Кликните, затем Cmd+V"}
        </Text>
      </div>
      <div onClick={() => inputRef.current?.click()} style={{ cursor: "pointer" }}>
        <Text as="span" size="small" tone="tertiary">
          Или{" "}
          <span
            style={{
              color: theme.accent.primary,
              textDecoration: "underline",
              cursor: "pointer",
            }}
          >
            выберите файл
          </span>
        </Text>
      </div>
      <input
        ref={inputRef}
        type="file"
        accept="image/*"
        multiple
        style={{ display: "none" }}
        onChange={(event: { target: HTMLInputElement }) => {
          addFiles(Array.from(event.target.files ?? []));
          event.target.value = "";
        }}
      />
      {shots.map((shot) => (
        <Stack key={shot.id} gap={4}>
          <img
            src={shot.src}
            alt="Скриншот кейса"
            style={{
              display: "block",
              maxWidth: 220,
              maxHeight: 160,
              width: "auto",
              height: "auto",
              objectFit: "contain",
            }}
          />
          <IconButton
            title="Удалить скриншот"
            size="sm"
            onClick={() => onChange((prev) => prev.filter((item) => item.id !== shot.id))}
          >
            ×
          </IconButton>
        </Stack>
      ))}
    </Stack>
  );
}

