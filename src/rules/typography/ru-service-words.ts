/** Короткие служебные слова (≤5 букв), длинные — раньше в alternation. */
export const RU_SERVICE_WORDS = Array.from(
  new Set([...RU_PREPOSITIONS, ...RU_CONJUNCTIONS, ...RU_PARTICLES]),
)
  .filter((w) => w.length <= 5)
  .sort((a, b) => b.length - a.length);

const SERVICE_WORDS_ALT = RU_SERVICE_WORDS.map(escapeRegex).join("|");

/** Регулярка: префикс + служебное слово + суффикс. */
export function serviceWordPattern(suffix: string, flags = "gim"): RegExp {
  return new RegExp(`${LATIN_CYRILLIC_WORD_EDGE}(${SERVICE_WORDS_ALT})${suffix}`, flags);
}
