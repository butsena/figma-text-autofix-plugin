function curatedRules() {
  return rowsToAutofixRules(parseReplacementRows(readFileSync(csvPath, "utf8")), "curated");
}

describe("покрытие старого словаря замен", () => {
  const rules = curatedRules();

  it("все прежние пары по смыслу сохраняются (регистр — capitalizeLike)", () => {
    for (const [from, to] of LEGACY_PAIRS) {
      const expected = to === "₽" ? "₽" : capitalizeLike(from, to);
      expect(applyAllRules(from, rules), from).toBe(expected);
      const titled = from.charAt(0).toUpperCase() + from.slice(1);
      const expectedTitle = to === "₽" ? "₽" : capitalizeLike(titled, to);
      expect(applyAllRules(titled, rules), titled).toBe(expectedTitle);
    }
  });

  it("полный набор правил плагина тоже правит он-лайн / online / промо-код / далее", () => {
    invalidateAutofixRulesCache();
    const all = getAutofixRules();
    const out = applyAllRules("Смотрите он-лайн и online и промо-кодов. Далее", all);
    expect(out).toContain("онлайн");
    expect(out).not.toMatch(/он[\s\u00A0\u2010-\u2014-]+лайн/i);
    expect(out).not.toMatch(/\bonline\b/i);
    expect(out).toContain("промокодов");
    expect(out).toContain("Дальше");
  });
});
