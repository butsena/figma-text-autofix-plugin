/**
 * Упаковывает Hunspell ru_RU (npm dictionary-ru / LibreOffice) в gzip+base64
 * для встраивания в бандл плагина.
 */
import fs from "node:fs";
import path from "node:path";
import { fileURLToPath } from "node:url";
import { gzipSync } from "node:zlib";

const root = path.resolve(path.dirname(fileURLToPath(import.meta.url)), "..");
const pkgDir = path.join(root, "node_modules", "dictionary-ru");
const outDir = path.join(root, "data", "hunspell");
const affPath = path.join(outDir, "ru_RU.aff");
const dicPath = path.join(outDir, "ru_RU.dic");
const pkgAff = path.join(pkgDir, "index.aff");
const pkgDic = path.join(pkgDir, "index.dic");

if (!fs.existsSync(affPath) || !fs.existsSync(dicPath)) {
  if (fs.existsSync(pkgAff) && fs.existsSync(pkgDic)) {
    fs.mkdirSync(outDir, { recursive: true });
    fs.copyFileSync(pkgAff, affPath);
    fs.copyFileSync(pkgDic, dicPath);
  } else {
    console.error("[build-hunspell] run npm install or npm run sync:spell-dictionary first");
    process.exit(1);
  }
}

const affGz = gzipSync(fs.readFileSync(affPath)).toString("base64");
const dicGz = gzipSync(fs.readFileSync(dicPath)).toString("base64");
const dicHead = fs.readFileSync(dicPath, "utf8").split("\n", 1)[0].trim();
const outPath = path.join(root, "src", "spell", "hunspell-dict.generated.ts");

const ts = `// Generated by scripts/build-hunspell-bundled.mjs — do not edit.
/** LibreOffice / Freedesktop ru_RU Hunspell (${dicHead} базовых записей + affix-правила). */
export const HUNSPELL_SOURCE = "dictionary-ru (LibreOffice dictionaries ru_RU, BSD-3-Clause)";
export const HUNSPELL_AFF_GZ_BASE64 = ${JSON.stringify(affGz)};
export const HUNSPELL_DIC_GZ_BASE64 = ${JSON.stringify(dicGz)};
`;

fs.mkdirSync(path.dirname(outPath), { recursive: true });
fs.writeFileSync(outPath, ts);
console.log(`[build-hunspell] wrote ${outPath} (dic entries header: ${dicHead})`);
