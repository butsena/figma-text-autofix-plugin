/**
 * Собирает компактный ё-словарь для IT / недвижимости из yo-sure.txt.
 * В списке только слова, где «е» вместо «ё» — орфографическая ошибка,
 * а не допустимый вариант (оплачен, оформлен, сохранен…).
 */
import fs from "node:fs";
import path from "node:path";
import { fileURLToPath } from "node:url";

const root = path.resolve(path.dirname(fileURLToPath(import.meta.url)), "..");
const dataDir = path.join(root, "data");
const generatedPath = path.join(root, "src/rules/yo-curated.generated.ts");

function readLines(filePath) {
  return fs
    .readFileSync(filePath, "utf8")
    .split(/\n/)
    .map((line) => line.replace(/#.*$/, "").trim())
    .filter(Boolean);
}

function toEForm(word) {
  return word.replace(/ё/g, "е").replace(/Ё/g, "Е");
}

const stems = readLines(path.join(dataDir, "yo-curated-stems.txt"));
const sure = readLines(path.join(dataDir, "yo-sure.txt"));
const unsure = new Set(readLines(path.join(dataDir, "yo-unsure.txt")));
const forceYo = readLines(path.join(dataDir, "yo-force-yo.txt"));

/** Редкие краткие прилагательные и омонимичные / шумные формы. */
const exclude =
  /^(?:найдён|расчётлив|отчётлив|учетверён|платёжеспособ|(?:расчёт|отчёт|учёт)(?:ен|на|но|ны)$)/i;

const yoForms = new Set();

for (const word of sure) {
  if (unsure.has(word)) continue;
  if (!/ё|Ё/.test(word)) continue;
  const lower = word.toLowerCase();
  if (exclude.test(lower)) continue;
  if (!stems.some((stem) => lower.startsWith(stem.toLowerCase()))) continue;
  yoForms.add(lower);
}

for (const word of forceYo) {
  if (!/ё|Ё/.test(word)) continue;
  yoForms.add(word.toLowerCase());
}

const sorted = [...yoForms].sort((a, b) => a.localeCompare(b, "ru"));
const corrections = {};
for (const right of sorted) {
  const wrong = toEForm(right).toLowerCase();
  if (wrong !== right) corrections[wrong] = right;
}

fs.writeFileSync(path.join(dataDir, "yo-curated.txt"), `${sorted.join("\n")}\n`);

const ts = `// Generated by scripts/build-yo-curated.mjs — do not edit.
export const YO_CORRECTIONS: Readonly<Record<string, string>> = ${JSON.stringify(corrections, null, 2)};
`;

fs.writeFileSync(generatedPath, ts);

console.log(
  `[build-yo-curated] ${sorted.length} форм, ${Object.keys(corrections).length} пар «е→ё»`,
);
